import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {resolve} from 'node:path';
import {createRequire} from 'node:module';
const require = createRequire(resolve('artifacts/firebase-tests/package.json'));
const {initializeTestEnvironment, assertSucceeds, assertFails} = require('@firebase/rules-unit-testing');
const {ref, set, get, remove, update, serverTimestamp, increment} = require('firebase/database');
const projectId = 'demo-mistik-metrics';
const rules = readFileSync('analytics/database.rules.template.json','utf8').replaceAll('ADMIN_EMAIL','admin@example.test');
const [host, port] = (process.env.FIREBASE_DATABASE_EMULATOR_HOST || '127.0.0.1:9099').split(':');
const env = await initializeTestEnvironment({projectId,database:{host,port:Number(port),rules}});
try {
  await env.clearDatabase();
  const claims = {firebase:{sign_in_provider:'anonymous'}};
  const client = env.authenticatedContext('install-a',claims).database();
  const stranger = env.authenticatedContext('install-b',claims).database();
  const admin = env.authenticatedContext('admin',{email:'admin@example.test',email_verified:true,firebase:{sign_in_provider:'google.com'}}).database();
  const unverified = env.authenticatedContext('unverified',{email:'admin@example.test',email_verified:false,firebase:{sign_in_provider:'google.com'}}).database();
  const wrongProvider = env.authenticatedContext('wrong',{email:'admin@example.test',email_verified:true,firebase:{sign_in_provider:'password'}}).database();
  const guest = env.unauthenticatedContext().database();
  const path = 'launcherMetrics/installations/install-a';
  await assertSucceeds(set(ref(client,path),{firstSeen:serverTimestamp(),lastSeen:serverTimestamp(),version:'6.2.14'}));
  const initial = (await assertSucceeds(get(ref(client,path)))).val();
  await assertFails(get(ref(guest,path))); await assertFails(get(ref(stranger,path)));
  await assertFails(get(ref(client,'launcherMetrics/installations')));
  await assertFails(set(ref(stranger,path),initial));
  await assertFails(set(ref(client,path),{...initial,firstSeen:initial.firstSeen+1}));
  await assertFails(set(ref(client,path),{...initial,email:'private@example.test'}));
  await assertFails(set(ref(client,path),{...initial,lastSeen:Date.now()-3600000}));
  await assertFails(set(ref(client,path),{...initial,lastSeen:Date.now()+120000}));
  await assertFails(set(ref(client,path),{...initial,version:'<script>'}));
  await assertSucceeds(set(ref(client,path),{...initial,lastSeen:serverTimestamp()}));
  await assertSucceeds(get(ref(admin,'launcherMetrics')));
  await assertFails(get(ref(unverified,'launcherMetrics'))); await assertFails(get(ref(wrongProvider,'launcherMetrics')));
  await assertFails(set(ref(admin,path),initial));
  const errorPath='launcherMetrics/errors/install-a/MLU-JAVA';
  const error = {lastSeen:serverTimestamp(),version:'6.2.14',code:'MLU-JAVA',count:increment(1)};
  await assertSucceeds(update(ref(client,errorPath),error));
  await assertSucceeds(update(ref(client,errorPath),error));
  assert.equal((await get(ref(admin,errorPath))).val().count,2);
  await assertFails(set(ref(client,errorPath),{...error,count:1000000001}));
  await assertFails(set(ref(client,errorPath),{...error,count:2}));
  await assertFails(set(ref(client,errorPath),{...error,count:increment(1),message:'raw stack'}));
  await assertFails(set(ref(client,'launcherMetrics/errors/install-a/UNKNOWN'),{...error,code:'UNKNOWN'}));
  await assertFails(set(ref(client,'launcherMetrics/errors/install-b/MLU-JAVA'),error));
  await assertSucceeds(set(ref(client,'launcherMetrics/sessions/install-a'),{lastSeen:serverTimestamp(),version:'6.2.14'}));
  await assertFails(get(ref(stranger,'launcherMetrics/sessions/install-a')));
  await assertFails(set(ref(stranger,'launcherMetrics/sessions/install-a'),{lastSeen:serverTimestamp(),version:'6.2.14'}));
  await assertSucceeds(remove(ref(client,'launcherMetrics/sessions/install-a')));
  await assertSucceeds(remove(ref(client,'launcherMetrics/errors/install-a')));
  await assertSucceeds(remove(ref(client,path)));
  await assertFails(set(ref(client,'launcherProfiles/install-a'),{name:'player'}));
  await assertFails(get(ref(admin,'activeSessions')));
  console.log('Firebase emulator: allow/deny and server increment checks passed.');
} finally { await env.cleanup(); }
